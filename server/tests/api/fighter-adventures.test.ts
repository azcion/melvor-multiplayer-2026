test('Adventure revisions reject duplicate settlement and preserve owner-only Inbox delivery',async()=>{
	expect((await post('/api/adventures/start',{})).status).toBe(401);
	const owner=await register_client('Adventurer',undefined,'1.7.6');
	const other=await register_client('Legacy adventurer',undefined,'1.7.5');
	await post_json('/api/combat/prepare',{command_id:crypto.randomUUID()},owner.session_token);
	const state_before=(await get_json_with_session<any>('/api/adventures/state',owner.session_token)).json;
	expect(state_before.tutorial_complete).toBe(false);
	await db_run("UPDATE combat_characters SET hitpoints=3 WHERE client_id=?",[owner.client_id]);
	await db_run("INSERT INTO combat_food_access(client_id,slot,tier,equipped_item) VALUES(?,'Food',1,'melvorD:Shrimp')",[owner.client_id]);
	const payload={revision:0,area_id:'melvorD:Goblin_Village',monster_ids:['melvorD:Golbin'],eligibility:{discovered:['melvorD:Bones'],owned_dlc:[]}};
	expect((await post_json<any>('/api/adventures/start',payload,owner.session_token)).json).toMatchObject({success:false,error:'tutorial_required'});
	expect((await post_json<any>('/api/adventures/capacity',{target:2,revision:0},owner.session_token)).json).toMatchObject({success:false,error:'tutorial_required'});
	await db_run('UPDATE combat_tutorial SET victories=7 WHERE client_id=?',[owner.client_id]);
	expect((await post('/api/adventures/start',{...payload,command_id:crypto.randomUUID()},owner.session_token)).status).toBe(400);
	expect((await post_json<any>('/api/adventures/start',{...payload,revision:'0'},owner.session_token)).json.error).toBe('adventure_changed');
	const first=(await post_json<any>('/api/adventures/start',payload,owner.session_token)).json;
	expect(first.success).toBe(true);
	expect((await post_json<any>('/api/adventures/start',payload,owner.session_token)).json.error).toBe('adventure_changed');
	await db_run('UPDATE fighter_adventures SET last_at=last_at-7200000 WHERE client_id=?',[owner.client_id]);
	const started=(await get_json_with_session<any>('/api/adventures/state',owner.session_token)).json;
	const check={revision:started.revision,reason:'login',eligibility:{discovered:[],owned_dlc:[]}};
	const checks=await Promise.all([1,2].map(()=>post_json<any>('/api/adventures/check-in',check,owner.session_token)));
	expect(checks.map(result=>result.json.success).sort()).toEqual([false,true]);
	expect(checks.find(result=>result.json.success)?.json).toEqual({success:true});
	expect((await post_json<any>('/api/adventures/stop',{revision:started.revision},owner.session_token)).json.error).toBe('adventure_changed');
	expect((await get_json_with_session<any>('/api/adventures/state',owner.session_token)).json.active_area).toBe(payload.area_id);
	expect((await get_json_with_session<any>('/api/adventures/state',other.session_token)).json.active_area).toBeNull();
	expect((await get_json_with_session<any>('/api/inbox',other.session_token)).json.items).toEqual([]);
	expect(await db_all("SELECT id FROM economy_receipts WHERE client_id=? AND kind LIKE 'adventure-%'",[owner.client_id])).toEqual([]);
	const legacy=(await get_json_with_session<any>('/api/events',owner.session_token)).json;
	expect(legacy.inbox_pending).toBe(true);expect(legacy.adventure_unread).toBeUndefined();
	const modern=(await get_json_with_session<any>('/api/events?adventures=1',owner.session_token)).json;
	expect(modern.adventure_items_pending).toBe(true);expect(modern.inbox_pending).toBe(false);expect(modern.adventure_unread).toBe(true);
	expect((await post_json<any>('/api/adventures/seen',{haul_revision:2},owner.session_token)).json.success).toBe(false);
	for (let attempt=0;attempt<2;attempt++)
		expect((await post_json<any>('/api/adventures/seen',{haul_revision:1},owner.session_token)).json.success).toBe(true);
	expect((await get_json_with_session<any>('/api/events?adventures=1',owner.session_token)).json.adventure_unread).toBe(false);
	expect((await get_json_with_session<any>('/api/inbox',owner.session_token)).json.items).toHaveLength(2);
 const claimPayload={existing_item_ids:[],available_slots:1};
 const claim=(await post_json<any>('/api/inbox/claim',claimPayload,owner.session_token)).json.claim;
 expect(claim.items.map((i:any)=>i.id).sort()).toEqual(['melvorD:Bones','melvorD:GP']);
 expect((await post_json<any>('/api/inbox/claim',claimPayload,owner.session_token)).json.claim).toEqual(claim);
 expect((await post('/api/inbox/acknowledge',{claim_id:claim.claim_id},other.session_token)).status).toBe(404);
 expect((await post_json<any>('/api/inbox/acknowledge',{claim_id:claim.claim_id},owner.session_token)).json.success).toBe(true);
 expect((await get_json_with_session<any>('/api/inbox',owner.session_token)).json.items).toHaveLength(0);
 expect((await post_json<any>('/api/adventures/check-in',check,owner.session_token)).json.error).toBe('adventure_changed');
 expect((await get_json_with_session<any>('/api/inbox',owner.session_token)).json.items).toHaveLength(0);
 const reloaded=(await get_json_with_session<any>('/api/adventures/state',owner.session_token)).json;
 await db_run('UPDATE fighter_adventures SET last_at=last_at-3600000 WHERE client_id=?',[owner.client_id]);
 // The new report applies after settlement. This haul still uses the empty report from the prior check-in.
 expect((await post_json<any>('/api/adventures/check-in',{...check,revision:reloaded.revision,eligibility:payload.eligibility},owner.session_token)).json.success).toBe(true);
 expect((await get_json_with_session<any>('/api/inbox',owner.session_token)).json.items.map((item:any)=>item.item_id)).toEqual(['melvorD:GP']);
 await post_json('/api/adventures/seen',{haul_revision:1},owner.session_token);
 expect((await get_json_with_session<any>('/api/events?adventures=1',owner.session_token)).json.adventure_unread).toBe(true);
});
test('Social Only and capacity mutations reject stale writes without repeating EP charges or refunds',async()=>{
	const owner=await register_client('Social adventurer',undefined,'1.7.6');
	const send=async(action:string,payload:Record<string,unknown>)=>(await post_json<any>(`/api/adventures/${action}`,payload,owner.session_token)).json;
	await post_json('/api/combat/prepare',{command_id:crypto.randomUUID()},owner.session_token);
	await db_run('UPDATE combat_tutorial SET victories=7 WHERE client_id=?',[owner.client_id]);
	await post_json('/api/social-mode/set',{mode:'social',command_id:crypto.randomUUID()},owner.session_token);
	await db_run("UPDATE combat_characters SET hitpoints=3 WHERE client_id=?",[owner.client_id]);
	await db_run("INSERT INTO combat_food_access(client_id,slot,tier,equipped_item) VALUES(?,'Food',1,'melvorD:Shrimp')",[owner.client_id]);
	const eligibility={discovered:['melvorD:Bones'],owned_dlc:[]};
	const state=async()=>(await get_json_with_session<any>('/api/adventures/state',owner.session_token)).json;
	expect((await send('start',{area_id:'melvorD:Goblin_Village',monster_ids:['melvorD:Golbin'],eligibility,revision:(await state()).revision})).error).toBe('opt_in_required');
	expect((await send('opt-in',{enabled:true,revision:(await state()).revision})).success).toBe(true);
	expect((await send('start',{area_id:'melvorD:Goblin_Village',monster_ids:['melvorD:Golbin'],eligibility,revision:(await state()).revision})).success).toBe(true);
	await db_run('UPDATE expedition_ep_balances SET points_micros=100000000 WHERE client_id=?',[owner.client_id]);
	const payload={revision:(await state()).revision,target:2};
	const purchases=await Promise.all([send('capacity',payload),send('capacity',payload)]);
	expect(purchases.map(result=>result.success).sort()).toEqual([false,true]);
	expect(await send('capacity',payload)).toEqual({success:false,error:'quote_changed'});
	const after=(await get_json_with_session<any>('/api/adventures/state',owner.session_token)).json;
	expect(after.capacity).toBe(2);expect(after.ep_micros).toBe(99000000);
	const reset={revision:after.revision};
	const refunded=await send('reset-capacity',reset);expect(refunded.success).toBe(true);
	expect(await send('reset-capacity',reset)).toEqual({success:false,error:'quote_changed'});
	expect((await get_json_with_session<any>('/api/adventures/state',owner.session_token)).json.ep_micros).toBe(99900000);
	const disable={enabled:false,revision:(await state()).revision};
	expect((await send('opt-in',disable)).success).toBe(true);
	expect((await send('opt-in',{enabled:true,revision:(await state()).revision})).success).toBe(true);
	expect((await send('opt-in',disable)).error).toBe('adventure_changed');
	expect((await state()).opted_in).toBe(true);
	expect(await db_all('SELECT amount_micros FROM combat_ep_ledger WHERE client_id=? ORDER BY id',[owner.client_id]))
		.toEqual([{amount_micros:-1000000},{amount_micros:900000}]);
	const held_revision=(await state()).revision;
	await db_run('INSERT INTO economy_client_holds(client_id,held,reason,created_at) VALUES(?,1,?,?)',[owner.client_id,'test hold',Date.now()]);
	expect((await send('capacity',{target:2,revision:held_revision})).success).toBe(false);
	expect((await state()).revision).toBe(held_revision);
});
